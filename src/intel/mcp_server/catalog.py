"""docs/mcp/CATALOG.md, generated from the code (profiles.yaml, the tools' own descriptions and labels, budgets.yaml)
so it can't drift: `intel mcp catalog` writes it, and a test fails when it is stale."""

from __future__ import annotations

import asyncio
import json
from pathlib import Path
from typing import Any

from intel.settings import repo_root

CATALOG = repo_root() / "docs" / "mcp" / "CATALOG.md"


async def _profile(profile: str, deps: Any) -> dict[str, Any]:
    from fastmcp import Client

    from intel.mcp_server.gateway import build_gateway

    async with Client(build_gateway(profile, deps)) as c:
        tools = await c.list_tools()
        prompts = await c.list_prompts()
    return {
        "tools": [
            {
                "name": t.name,
                "sensitivity": (t.meta or {}).get("dk/sensitivity"),
                "server": (t.meta or {}).get("dk/server"),
                "summary": (t.description or "").split(". ")[0].removeprefix("Use when: ").strip(),
                "tokens": len(json.dumps(t.model_dump(mode="json", exclude_none=True))) // 3,
            }
            for t in tools
        ],
        "prompts": sorted(p.name for p in prompts),
    }


def render(deps: Any) -> str:
    from intel.mcp_server.gateway import TOOLS_API, budgets, profiles

    data = {p: asyncio.run(_profile(p, deps)) for p in profiles()}
    b = budgets()
    lines = [
        "# dk_intel catalog",
        "",
        f"Generated by `uv run intel mcp catalog` from the code (tools API {TOOLS_API}); do not edit by hand.",
        "Connect: stdio `intel mcp serve --profile <p>`, or HTTP `http://127.0.0.1:8766/mcp/<p>/` with a token "
        "(see [CLIENTS.md](CLIENTS.md)).",
        "",
        "## Profiles",
        "",
        "| Profile | Tools | Tool list (tokens, est.) | Prompts |",
        "|---|---|---|---|",
    ]
    for p, d in data.items():
        total = sum(t["tokens"] for t in d["tools"])
        lines.append(f"| `{p}` | {len(d['tools'])} | {total:,} | {', '.join(d['prompts']) or '—'} |")
    lines += [
        "",
        "## Tools",
        "",
        "| Tool | Server | Data class | Result budget (tokens) | Profiles | Use when |",
        "|---|---|---|---|---|---|",
    ]
    owner = {t["name"]: t for t in data["owner"]["tools"]}
    for name, t in owner.items():
        who = ", ".join(p for p, d in data.items() if any(x["name"] == name for x in d["tools"]))
        summary = t["summary"].replace("|", "/").replace("\n", " ")
        server = str(t["server"]).removeprefix("dk_")
        lines.append(f"| `{name}` | {server} | {t['sensitivity']} | {b.get(name, '—')} | {who} | {summary} |")
    lines += [
        "",
        "Data classes: S0 public, S1 internal, S2 third-party text (untrusted; a token with `--max-sensitivity S1` "
        "never sees these tools).",
        "",
    ]
    return "\n".join(lines)


def write(deps: Any, path: Path = CATALOG) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(deps))
